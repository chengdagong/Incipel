export type TKey = keyof typeof DICT.zh;
type Vars = Record<string, string | number>;

// {name}/{n} 占位替换;未给的占位原样保留。
function interpolate(s: string, vars?: Vars): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_m, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export type I18nApi = {
  lang: Lang;
  setLang: (l: Lang) => void;
  // 取文案;缺当前语言时回落简体中文,再回落 key 本身。
  t: (key: TKey, vars?: Vars) => string;
};

const I18nContext = createContext<I18nApi | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('zh');

  // 启动时读回上次选择(默认简体中文)。
  useEffect(() => {
    let mounted = true;
    AsyncStorage.getItem(LANG_STORAGE_KEY)
      .then((v) => {
        if (mounted && v && v in DICT) setLangState(v as Lang);
      })
      .catch(() => {
        // 读取失败(如存储不可用)不阻塞,留默认语言。
      });
    return () => {
      mounted = false;
    };
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    void AsyncStorage.setItem(LANG_STORAGE_KEY, l).catch(() => {});
  }, []);

  const t = useCallback(
    (key: TKey, vars?: Vars) => interpolate(DICT[lang]?.[key] ?? DICT.zh[key] ?? String(key), vars),
    [lang],
  );

  const api = useMemo<I18nApi>(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={api}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nApi {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n 必须在 I18nProvider 内使用');
  return ctx;
}

// 便捷:只取 t(）。
export function useT(): I18nApi['t'] {
  return useI18n().t;
}
